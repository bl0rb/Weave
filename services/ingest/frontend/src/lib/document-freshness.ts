/**
 * Client of the 'Aktualität & Änderungen' surface (backend:
 * app/api/document_freshness.py, schemas in app/schemas/document_freshness.py):
 * review dates of a document version ('Prüfung & Aktualität' on
 * /reviews/[id]), the section-aware version comparison
 * (/reviews/[id]/changes) and the personal change feed with topic
 * subscriptions (/aenderungen).
 */

/** Window event the change feed fires after marking notifications read, so the sidebar badge refreshes at once. */
export const CHANGES_CHANGED_EVENT = 'weave:changes-changed';
export const CHANGE_PAGE_SIZE = 25;

/** `PortalDocumentDetail.review` and the answer of PUT /review and POST /review/confirm. */
export type DocumentReview = {
  review_due_at: string | null; last_reviewed_at: string | null;
  /** A username, never more. */
  last_reviewed_by: string | null;
  overdue: boolean;
};

export type DocumentDiffVersion = { job_id: string; document_version: number; created_at: string | null };
export type DocumentDiffStats = { added_lines: number; removed_lines: number; sections_added: number; sections_removed: number; sections_changed: number };
export type DocumentDiffHunk = { op: 'equal' | 'insert' | 'delete' | 'replace'; base: string[]; target: string[] };
export type DocumentDiffSection = {
  heading_path: string[]; change: 'added' | 'removed' | 'changed';
  added_lines: number; removed_lines: number; hunks: DocumentDiffHunk[];
};
export type DocumentDiff = {
  base: DocumentDiffVersion; target: DocumentDiffVersion; stats: DocumentDiffStats;
  /** German, human readable (generated by the backend). */
  summary: string[];
  sections: DocumentDiffSection[];
};

export type ChangeCollectionRef = { id: string; name: string; slug: string };
export type TopicSubscription = {
  id: string; label: string; query: string | null;
  /** The normalised keywords the matcher uses. */
  terms: string[];
  collection: ChangeCollectionRef | null; created_at: string;
};
export type TopicSubscriptionInput = { collection_id?: string; query?: string; label?: string };
export type ChangeSummary = { stats: DocumentDiffStats | null; lines: string[] };
export type ChangeNotification = {
  id: string; subscription: { id: string; label: string } | null;
  job_id: string; previous_job_id: string | null; document_version: number | null;
  collection: ChangeCollectionRef; change_type: 'new' | 'updated'; title: string;
  summary: ChangeSummary; matched_terms: string[]; read_at: string | null; created_at: string;
};
export type ChangeNotificationPage = { items: ChangeNotification[]; total: number; page: number; page_size: number };
export type ChangeSearchItem = {
  job_id: string; previous_job_id: string | null; document_version: number;
  collection: ChangeCollectionRef; change_type: 'new' | 'updated'; title: string; released_at: string;
  summary: ChangeSummary; matched_terms: string[];
};
export type ChangeSearchResult = {
  items: ChangeSearchItem[]; terms: string[];
  /** The backend's per-request scan cap stopped the search before older releases were checked (narrow the period or pick a space). */
  incomplete?: boolean;
};

const documentPath = (jobId: string) => `/api/v1/portal/documents/${encodeURIComponent(jobId)}`;

/** Set (a `YYYY-MM-DD` date) or clear (null) when this version is next due for review. */
export function setDocumentReviewDue(jobId: string, reviewDueAt: string | null): Promise<DocumentReview> {
  return apiJson(`${documentPath(jobId)}/review`, { ...jsonBody({ review_due_at: reviewDueAt }), method: 'PUT' });
}

/** 'Als geprüft bestätigen': next due date = the space's interval (or none) unless a date is given. */
export function confirmDocumentReview(jobId: string, reviewDueAt?: string): Promise<DocumentReview> {
  return apiJson(`${documentPath(jobId)}/review/confirm`, reviewDueAt ? jsonBody({ review_due_at: reviewDueAt }) : { method: 'POST' });
}

/** Compare `jobId` with `base` (default: its previous version). */
export function loadDocumentDiff(jobId: string, base?: string | null, signal?: AbortSignal): Promise<DocumentDiff> {
  const params = base ? `?${new URLSearchParams({ base })}` : '';
  return apiJson(`${documentPath(jobId)}/diff${params}`, { cache: 'no-store', signal });
}

/**
 * The caller's visible versions of a document chain, newest first. A
 * password-protected job answers 401 here: that must not log the (valid)
 * session out, hence skipAuthRedirect (same as the artifacts request).
 */
export async function loadDocumentVersions(jobId: string, signal?: AbortSignal): Promise<JobVersionEntry[]> {
  const page = await apiJson<JobVersionsResponse>(`/api/v1/jobs/${encodeURIComponent(jobId)}/versions`, { cache: 'no-store', signal, skipAuthRedirect: true });
  return Array.isArray(page?.items) ? page.items : [];
}

/**
 * The versions that can take part in a comparison: only FINISHED ones have
 * markdown (a PENDING/RUNNING/FAILED version would diff as "everything
 * added"). Keeps the input order (newest first).
 */
export function comparableVersions(versions: JobVersionEntry[]): JobVersionEntry[] {
  return versions.filter(version => version.status === 'FINISHED');
}

/**
 * The version the comparison starts from by default: the next older visible
 * FINISHED version than `jobId` (the backend's default is the direct
 * predecessor, which the caller may not see or which may have failed). null
 * when `jobId` is the oldest.
 */
export function defaultBaseVersion(versions: JobVersionEntry[], jobId: string): JobVersionEntry | null {
  const target = versions.find(version => version.job_id === jobId);
  if (!target) return null;
  return comparableVersions(versions)
    .filter(version => version.document_version < target.document_version)
    .sort((a, b) => b.document_version - a.document_version)[0] ?? null;
}

/**
 * Where 'Versionen vergleichen' leads from `jobId`: its comparison with the
 * next older FINISHED version, or -- when `jobId` is the oldest one -- the
 * newest FINISHED version compared with `jobId`. null when there is nothing
 * to compare (fewer than two FINISHED versions, or `jobId` is not one).
 */
export function compareLink(versions: JobVersionEntry[], jobId: string): { target: string; base: string } | null {
  const comparable = comparableVersions(versions);
  if (comparable.length < 2 || !comparable.some(version => version.job_id === jobId)) return null;
  const base = defaultBaseVersion(versions, jobId);
  if (base) return { target: jobId, base: base.job_id };
  const newest = [...comparable].sort((a, b) => b.document_version - a.document_version)[0];
  return { target: newest.job_id, base: jobId };
}

/**
 * Whether a newer visible version of `jobId`'s chain has been released, i.e.
 * `jobId` is superseded and the review writers answer 409
 * (`has_newer_release`, app/services/document_freshness.py). The versions
 * list has no release flag, so the (few) newer FINISHED versions' portal
 * details are asked; failures count as "not released" -- the backend still
 * refuses, and the panel maps that 409. Newer versions the caller cannot
 * see are only caught by that 409.
 */
export async function hasNewerRelease(versions: JobVersionEntry[], jobId: string, signal?: AbortSignal): Promise<boolean> {
  const target = versions.find(version => version.job_id === jobId);
  if (!target) return false;
  const newer = comparableVersions(versions).filter(version => version.document_version > target.document_version);
  const released = await Promise.all(newer.map(version =>
    apiJson<{ release?: unknown }>(documentPath(version.job_id), { cache: 'no-store', signal, skipAuthRedirect: true })
      .then(detail => Boolean(detail?.release))
      .catch(() => false)));
  return released.some(Boolean);
}

export function loadSubscriptions(signal?: AbortSignal): Promise<{ items: TopicSubscription[] }> {
  return apiJson('/api/v1/portal/subscriptions', { cache: 'no-store', signal });
}

export function createSubscription(input: TopicSubscriptionInput): Promise<TopicSubscription> {
  return apiJson('/api/v1/portal/subscriptions', jsonBody(input));
}

/** DELETE answers 204 without a body, so this cannot go through apiJson. */
export async function deleteSubscription(id: string): Promise<void> {
  const res = await apiFetch(`/api/v1/portal/subscriptions/${encodeURIComponent(id)}`, { method: 'DELETE' });
  if (!res.ok) throw new ApiError(res.status, `Request failed with status ${res.status}`);
}

export function loadChanges(options: { unread?: boolean; page?: number; pageSize?: number } = {}, signal?: AbortSignal): Promise<ChangeNotificationPage> {
  const params = new URLSearchParams({ page: String(options.page ?? 1), page_size: String(options.pageSize ?? CHANGE_PAGE_SIZE) });
  if (options.unread) params.set('unread', 'true');
  return apiJson(`/api/v1/portal/changes?${params}`, { cache: 'no-store', signal });
}

/** Mark own notifications read: the given ids, or all of them. */
export function markChangesRead(target: { ids: string[] } | { all: true }): Promise<{ updated: number }> {
  return apiJson('/api/v1/portal/changes/read', jsonBody(target));
}

/** Unread notifications -- the sidebar badge. */
export function loadChangeCount(signal?: AbortSignal): Promise<{ unread: number }> {
  return apiJson('/api/v1/portal/changes/count', { cache: 'no-store', signal });
}

/** 'Was hat sich geändert?': released new versions of the last `days` days matching every keyword of `q`. */
export function searchChanges(options: { q?: string; collectionId?: string; days?: number } = {}, signal?: AbortSignal): Promise<ChangeSearchResult> {
  const params = new URLSearchParams({ days: String(options.days ?? 30) });
  const q = options.q?.trim();
  if (q) params.set('q', q);
  if (options.collectionId) params.set('collection_id', options.collectionId);
  return apiJson(`/api/v1/portal/changes/search?${params}`, { cache: 'no-store', signal });
}

/** `YYYY-MM-DD` of an ISO timestamp, for a date input. Review dates are UTC midnights (app/services/document_freshness.py). */
export function dateInputValue(value: string | null | undefined): string {
  if (!value) return '';
  const date = new Date(value);
  return Number.isNaN(date.getTime()) ? '' : date.toISOString().slice(0, 10);
}

/** Link to the comparison of a changed document (new documents open the document itself). */
export function changeHref(change: { job_id: string; previous_job_id: string | null; change_type: string }): string {
  const target = encodeURIComponent(change.job_id);
  if (change.change_type !== 'updated' || !change.previous_job_id) return `/reviews/${target}`;
  return `/reviews/${target}/changes?${new URLSearchParams({ base: change.previous_job_id })}`;
}
