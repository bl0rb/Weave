def test_teams_transcript_is_rendered_as_speaker_turns():
    markdown = vtt_to_markdown(TEAMS_VTT, title='Budget-Runde')

    assert markdown.startswith('# Budget-Runde\n\n')
    assert '**Teilnehmende:** Max Mustermann, Anna Beispiel' in markdown
    assert '**Dauer:** 00:00:41' in markdown
    # Boilerplate and non-speech annotations are gone.
    assert 'Transcription has started' not in markdown
    assert 'joined the meeting' not in markdown
    assert 'Musik' not in markdown
    assert 'unverständlich' not in markdown
    assert 'Generated by Microsoft Teams' not in markdown
    assert 'color: white' not in markdown
    # Roll-up duplicates collapsed into one turn with one timestamp.
    assert markdown.count('Guten Morgen zusammen') == 1
    assert '**Max Mustermann** [00:00:03]: Guten Morgen zusammen, wir starten mit dem Budget.' in markdown
    # Inline tags dropped, entities decoded, real parentheses kept.
    assert '**Anna Beispiel** [00:00:12]: Das Budget f&uuml;r Q4 ist freigegeben & verbucht.' in markdown
    # A silence > 8 s starts a new turn for the same speaker.
    assert '**Anna Beispiel** [00:00:30]: Nach der Pause: Deadline (wie besprochen) bleibt Freitag.' in markdown
    assert '**Max Mustermann** [00:00:40]: Danke, dann sind wir durch.' in markdown
    # Cue identifiers never leak into the text.
    assert '0f1b2c3d' not in markdown


def test_zoom_inline_speaker_prefix_is_promoted_only_when_recurring():
    vtt = (
        'WEBVTT\n\n'
        '1\n00:00:00.000 --> 00:00:02.000\nLisa Lang: Hallo zusammen.\n\n'
        '2\n00:00:02.000 --> 00:00:04.000\nLisa Lang: Hinweis: morgen ist Abgabe.\n\n'
        '3\n00:00:04.000 --> 00:00:06.000\nTom Kurz: Verstanden.\n\n'
        '4\n00:00:06.000 --> 00:00:08.000\nTom Kurz: Ich übernehme das.\n\n'
        '5\n00:00:08.000 --> 00:00:10.000\nAchtung: das ist nur ein Satz, kein Sprecher.\n'
    )
    markdown = vtt_to_markdown(vtt)

    assert '**Teilnehmende:** Lisa Lang, Tom Kurz' in markdown
    assert '**Lisa Lang** [00:00:00]: Hallo zusammen. Hinweis: morgen ist Abgabe.' in markdown
    assert '**Tom Kurz** [00:00:04]: Verstanden. Ich übernehme das.' in markdown
    assert '[00:00:08] Achtung: das ist nur ein Satz, kein Sprecher.' in markdown
    assert '**Achtung**' not in markdown


def test_transcript_without_speakers_breaks_on_silence_and_accepts_srt_commas():
    vtt = (
        'WEBVTT\n\n'
        '00:00:00,000 --> 00:00:02,000\nErster Satz.\n\n'
        '00:00:02,000 --> 00:00:04,000\nZweiter Satz.\n\n'
        '00:00:20,000 --> 00:00:22,000\nNach langer Pause.\n'
    )
    markdown = vtt_to_markdown(vtt)

    assert 'Teilnehmende' not in markdown
    assert '[00:00:00] Erster Satz. Zweiter Satz.' in markdown
    assert '[00:00:20] Nach langer Pause.' in markdown


def test_boilerplate_only_transcript_yields_placeholder():
    vtt = (
        'WEBVTT\n\n'
        '00:00:00.000 --> 00:00:02.000\n<v System>Recording in progress</v>\n\n'
        '00:00:02.000 --> 00:00:04.000\nDiese Besprechung wird aufgezeichnet.\n\n'
        '00:00:04.000 --> 00:00:06.000\nLive captions are now on.\n'
    )
    assert parse_vtt(vtt) == []
    assert 'keine verwertbaren' in vtt_to_markdown(vtt)


def test_hour_timestamps_and_cue_settings_are_parsed():
    vtt = 'WEBVTT\n\n01:02:03.456 --> 01:02:05.000 line:0 position:50%\n<v A>Spät am Tag.</v>\n'
    cues = parse_vtt(vtt)
    assert len(cues) == 1
    assert cues[0].start == 3723.456
    assert cues[0].speaker == 'A'
    assert '**A** [01:02:03]: Spät am Tag.' in vtt_to_markdown(vtt)
